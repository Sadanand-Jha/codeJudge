"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import {
  ArrowLeftRight,
  BookOpen,
  CalendarClock,
  Coins,
  FileText,
  History,
  MessageSquare,
  RefreshCw,
  RotateCcw,
  ShoppingCart,
  Sparkles,
  type LucideIcon,
} from "lucide-react";
import { cn } from "@/lib/helpers";
import { getUserTimeZone } from "@/lib/timezone";
import { useAICreditsStore } from "@/store/aiCreditsStore";
import {
  getCreditTransactions,
  type CreditLedgerEntry,
  type CreditLedgerFilter,
  type CreditSpendSummary,
} from "@/services/billing";
import {
  BillButton,
  EmptyState,
  ErrorState,
  PageHeader,
  Panel,
  SegmentedControl,
  Skeleton,
  StatCard,
} from "./ui";

const PAGE_SIZE = 25;

interface ReasonMeta {
  label: string;
  description: string;
  icon: LucideIcon;
}

const REASON_META: Record<string, ReasonMeta> = {
  ai_chat: {
    label: "AI chat",
    description: "Conversation with the AI assistant",
    icon: MessageSquare,
  },
  ai_chat_files: {
    label: "AI chat with files",
    description: "AI assistant with uploaded documents",
    icon: FileText,
  },
  ai_generate_questions: {
    label: "Question generation",
    description: "Questions generated from your material",
    icon: Sparkles,
  },
  ai_generate_bank: {
    label: "Question generation",
    description: "Questions generated by topic",
    icon: BookOpen,
  },
  ai_generate_problems: {
    label: "Question generation",
    description: "Questions generated from your material",
    icon: Sparkles,
  },
  ai_generate_sections: {
    label: "Section generation",
    description: "Exam structure generated from your files",
    icon: FileText,
  },
  ai_generate_paper: {
    label: "Question paper generation",
    description: "Full paper generated from your sections",
    icon: FileText,
  },
  ai_refund: {
    label: "AI credit refund",
    description: "Credits returned for a failed AI request",
    icon: RotateCcw,
  },
  credit_pack_purchase: {
    label: "Credit pack purchase",
    description: "Credits added from a purchase",
    icon: ShoppingCart,
  },
  plan_credit_grant: {
    label: "Monthly plan credits",
    description: "Credits included with your plan",
    icon: CalendarClock,
  },
  refund: {
    label: "Payment refund adjustment",
    description: "Credits removed by a payment refund",
    icon: RotateCcw,
  },
};

function reasonMeta(reason: string): ReasonMeta {
  return (
    REASON_META[reason] ?? {
      label: reason.replaceAll("_", " "),
      description: "Credit balance activity",
      icon: Coins,
    }
  );
}

function formatDateTime(iso: string): string {
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return "Unknown date";
  return date.toLocaleString("en-IN", {
    timeZone: getUserTimeZone(),
    day: "numeric",
    month: "short",
    year: "numeric",
    hour: "numeric",
    minute: "2-digit",
  });
}

function referenceLabel(entry: CreditLedgerEntry): string | null {
  if (entry.orderNo) return `Order #${entry.orderNo}`;
  if (entry.refId) return `Ref ${entry.refId.slice(0, 8)}`;
  return null;
}

function errorMessage(error: unknown): string {
  return error instanceof Error
    ? error.message
    : "Your credit activity could not be loaded.";
}

function LedgerRow({ entry }: { entry: CreditLedgerEntry }) {
  const meta = reasonMeta(entry.reason);
  const Icon = meta.icon;
  const spent = entry.amount < 0;
  const reference = referenceLabel(entry);

  return (
    <li className="flex flex-col gap-3 px-4 py-4 sm:flex-row sm:items-center sm:px-5">
      <span
        className={cn(
          "grid h-10 w-10 shrink-0 place-items-center rounded-xl",
          spent
            ? "bg-[var(--qs-brand)]/10 text-[var(--qs-brand)]"
            : "bg-[var(--qs-okbg)] text-[var(--qs-ok)]"
        )}
        aria-hidden="true"
      >
        <Icon className="h-4 w-4" />
      </span>

      <div className="min-w-0 flex-1">
        <div className="flex flex-wrap items-center gap-2">
          <p className="text-[13px] font-bold text-[var(--qs-ink)]">{meta.label}</p>
          <span
            className={cn(
              "rounded-full px-2 py-0.5 text-[10px] font-extrabold uppercase tracking-wide",
              spent
                ? "bg-[var(--qs-brand)]/10 text-[var(--qs-brand)]"
                : "bg-[var(--qs-okbg)] text-[var(--qs-ok)]"
            )}
          >
            {spent ? "Spent" : "Added"}
          </span>
        </div>
        <p className="mt-0.5 text-[11px] leading-5 text-[var(--qs-muted)]">
          {meta.description}
        </p>
        <p className="mt-1 text-[11px] tabular-nums text-[var(--qs-muted)]">
          {formatDateTime(entry.createdAt)}
          {reference ? ` · ${reference}` : ""}
        </p>
      </div>

      <div className="flex shrink-0 items-end justify-between gap-3 sm:flex-col sm:items-end sm:justify-center">
        <p
          className={cn(
            "text-[19px] font-extrabold leading-none tabular-nums",
            spent ? "text-[var(--qs-ink)]" : "text-[var(--qs-ok)]"
          )}
        >
          {spent ? "−" : "+"}
          {Math.abs(entry.amount).toLocaleString("en-IN")}
          <span className="ml-1 text-[10px] font-bold uppercase tracking-wide text-[var(--qs-muted)]">
            credits
          </span>
        </p>
        {entry.balanceAfter !== null && (
          <p className="text-[10px] text-[var(--qs-muted)]">
            Balance after: {entry.balanceAfter.toLocaleString("en-IN")}
          </p>
        )}
      </div>
    </li>
  );
}

function LoadingRows() {
  return (
    <div className="divide-y divide-[var(--qs-line)]">
      {[0, 1, 2, 3, 4].map((row) => (
        <div key={row} className="flex items-center gap-3 px-4 py-4 sm:px-5">
          <Skeleton className="h-10 w-10 shrink-0 rounded-xl" />
          <div className="flex-1 space-y-2">
            <Skeleton className="h-3.5 w-40" />
            <Skeleton className="h-3 w-56 max-w-full" />
          </div>
          <Skeleton className="h-5 w-16 shrink-0" />
        </div>
      ))}
    </div>
  );
}

export function CreditUsagePage() {
  const balance = useAICreditsStore((state) => state.balance);
  const balanceLoaded = useAICreditsStore((state) => state.lastFetchedAt !== null);
  const refreshCredits = useAICreditsStore((state) => state.refresh);

  const [filter, setFilter] = useState<CreditLedgerFilter>("spent");
  const [entries, setEntries] = useState<CreditLedgerEntry[]>([]);
  const [summary, setSummary] = useState<CreditSpendSummary | null>(null);
  const [hasMore, setHasMore] = useState(false);
  const [loading, setLoading] = useState(true);
  const [loadingMore, setLoadingMore] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const requestId = useRef(0);

  const load = useCallback(
    async (type: CreditLedgerFilter, offset: number, append: boolean) => {
      const currentRequest = ++requestId.current;
      if (append) {
        setLoadingMore(true);
      }

      try {
        const page = await getCreditTransactions({
          limit: PAGE_SIZE,
          offset,
          type,
        });
        if (currentRequest !== requestId.current) return;
        setEntries((previous) =>
          append ? [...previous, ...page.entries] : page.entries
        );
        setSummary(page.summary);
        setHasMore(page.hasMore);
      } catch (loadError) {
        if (currentRequest !== requestId.current) return;
        if (!append) setError(errorMessage(loadError));
      } finally {
        if (currentRequest === requestId.current) {
          setLoading(false);
          setLoadingMore(false);
        }
      }
    },
    []
  );

  const handleFilterChange = useCallback((next: CreditLedgerFilter) => {
    setLoading(true);
    setError(null);
    setFilter(next);
  }, []);

  const retry = useCallback(() => {
    setLoading(true);
    setError(null);
    void load(filter, 0, false);
    void refreshCredits({ force: true });
  }, [filter, load, refreshCredits]);

  useEffect(() => {
    const timer = setTimeout(() => {
      void load(filter, 0, false);
    }, 0);
    return () => clearTimeout(timer);
  }, [filter, load]);

  useEffect(() => {
    void refreshCredits();
  }, [refreshCredits]);

  const emptyDescription =
    filter === "spent"
      ? "AI chat and question generation will appear here as soon as they use credits."
      : filter === "added"
        ? "Credit pack purchases and monthly plan credits will appear here."
        : "Spends, refunds, purchases and plan grants will appear here.";

  return (
    <div className="space-y-5 pb-2">
      <PageHeader
        title="Credit usage"
        subtitle="See exactly where your AI credits were spent."
        actions={
          <>
            <BillButton
              variant="outline"
              href="/creator/billing/transactions"
              icon={<ArrowLeftRight className="h-4 w-4" />}
            >
              Transactions
            </BillButton>
            <BillButton
              href="/creator/billing/credits"
              icon={<Coins className="h-4 w-4" />}
            >
              Buy credits
            </BillButton>
          </>
        }
      />

      <div className="grid gap-3 sm:grid-cols-3">
        <StatCard
          label="Available credits"
          value={balance.totalRemaining}
          display={
            balanceLoaded
              ? balance.totalRemaining.toLocaleString("en-IN")
              : "—"
          }
          hint="Plan + purchased credits"
          icon={<Coins className="h-4 w-4" />}
        />
        <StatCard
          label="Spent this month"
          value={summary?.spentThisMonth ?? 0}
          display={
            summary ? summary.spentThisMonth.toLocaleString("en-IN") : "—"
          }
          hint="AI usage only"
          accent="warning"
          icon={<History className="h-4 w-4" />}
        />
        <StatCard
          label="Total spent"
          value={summary?.totalSpent ?? 0}
          display={summary ? summary.totalSpent.toLocaleString("en-IN") : "—"}
          hint={`${(summary?.spendCount ?? 0).toLocaleString("en-IN")} AI ${
            summary?.spendCount === 1 ? "request" : "requests"
          }`}
          accent="info"
          icon={<ArrowLeftRight className="h-4 w-4" />}
        />
      </div>

      <Panel
        title="Credit activity"
        subtitle={
          filter === "spent"
            ? "Every AI request that used credits, newest first."
            : filter === "added"
              ? "Credits added from purchases, plans and refunds."
              : "All credit spends and additions, newest first."
        }
        action={
          <SegmentedControl
            options={[
              { id: "spent", label: "Spent" },
              { id: "added", label: "Added" },
              { id: "all", label: "All activity" },
            ]}
            value={filter}
            onChange={handleFilterChange}
          />
        }
        noPadding
      >
        {loading ? (
          <LoadingRows />
        ) : error ? (
          <div className="p-5 sm:p-6">
            <ErrorState
              message={error}
              onRetry={retry}
            />
          </div>
        ) : entries.length === 0 ? (
          <div className="p-5 sm:p-6">
            <EmptyState
              icon={<Coins className="h-6 w-6" />}
              title={
                filter === "spent"
                  ? "No credits spent yet"
                  : filter === "added"
                    ? "No credits added yet"
                    : "No credit activity yet"
              }
              description={emptyDescription}
              action={
                <BillButton
                  href="/creator/billing/credits"
                  icon={<Coins className="h-4 w-4" />}
                >
                  Buy credits
                </BillButton>
              }
            />
          </div>
        ) : (
          <>
            <ul className="divide-y divide-[var(--qs-line)]">
              {entries.map((entry) => (
                <LedgerRow key={entry.id} entry={entry} />
              ))}
            </ul>
            <div className="flex flex-col gap-3 border-t-2 border-[var(--qs-line)] px-4 py-3.5 sm:flex-row sm:items-center sm:justify-between sm:px-5">
              <p className="text-[11px] tabular-nums text-[var(--qs-muted)]">
                Showing {entries.length.toLocaleString("en-IN")}{" "}
                {entries.length === 1 ? "entry" : "entries"}
              </p>
              {hasMore && (
                <BillButton
                  variant="outline"
                  loading={loadingMore}
                  onClick={() => void load(filter, entries.length, true)}
                  icon={<RefreshCw className="h-3.5 w-3.5" />}
                >
                  Load more
                </BillButton>
              )}
            </div>
          </>
        )}
      </Panel>
    </div>
  );
}
